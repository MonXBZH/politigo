// Builds web/emoji-data.mjs, the chat's standard emoji pack, from Unicode's emoji-test.txt (Emoji 14.0, 2021: shown by
// every phone and PC still updated, where a newer emoji would show as an empty box).
// Usage: curl -sSfLO https://unicode.org/Public/emoji/14.0/emoji-test.txt && node tools/emoji-data.mjs emoji-test.txt
// Kept: the fully-qualified emojis, without skin-tone variants (the default yellow only), the "Component" group
// (skin tones and hair alone), the flags (on Windows a flag shows as two letters: "FR") and the letters of the
// "alphanum" subgroup (🅰️ 🆗 Ⓜ️...). The French and Soviet flags come as the chat's own images (CUSTOM in chat.mjs).
import {readFileSync,writeFileSync} from "node:fs";

const src=process.argv[2];
if(!src){console.error("Usage: node tools/emoji-data.mjs emoji-test.txt");process.exit(1);}
const LABEL={"Smileys & Emotion":"Visages","People & Body":"Personnes","Animals & Nature":"Animaux et nature","Food & Drink":"Nourriture",
 "Travel & Places":"Voyages et lieux","Activities":"Activités","Objects":"Objets","Symbols":"Symboles"};
const SKIP_SUB=new Set(["alphanum"]);
const groups=new Map();let group="",sub="";
for(const line of readFileSync(src,"utf8").split("\n")){
 let m;
 if((m=/^# group: (.+)$/.exec(line))){group=m[1].trim();continue;}
 if((m=/^# subgroup: (.+)$/.exec(line))){sub=m[1].trim();continue;}
 if(!LABEL[group]||SKIP_SUB.has(sub))continue;
 if(!(m=/^[0-9A-F ]+;\s*fully-qualified\s*#\s*(\S+)/.exec(line)))continue;
 const e=m[1];
 if(/[\u{1F3FB}-\u{1F3FF}]/u.test(e))continue;   // a skin-tone variant
 let list=groups.get(LABEL[group]);if(!list)groups.set(LABEL[group],list=[]);
 list.push(e);
}
const total=[...groups.values()].reduce((n,l)=>n+l.length,0);
const out=`// Generated by tools/emoji-data.mjs from Unicode's emoji-test.txt (Emoji 14.0): do not edit by hand.
// The chat's standard emoji pack, by category, each a space-separated list. No skin-tone variants, flags or letters.
export const EMOJI_GROUPS=[
${[...groups].map(([k,l])=>` [${JSON.stringify(k)},${JSON.stringify(l.join(" "))}]`).join(",\n")}
];
`;
writeFileSync(new URL("../web/emoji-data.mjs",import.meta.url),out);
console.log(`web/emoji-data.mjs: ${total} emojis in ${groups.size} categories.`);
